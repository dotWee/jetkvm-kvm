package rfb

// KeysymToHID maps an X11 keysym to a USB HID Usage ID.
// Returns the HID key code, whether it's a modifier key, and whether the
// keysym was found in the mapping.
func KeysymToHID(keysym uint32) (hidKey byte, isModifier bool, found bool) {
	// Check modifier keys first
	if hid, ok := modifierKeysymMap[keysym]; ok {
		return hid, true, true
	}

	// Check regular keys
	if hid, ok := keysymMap[keysym]; ok {
		return hid, false, true
	}

	return 0, false, false
}

// X11 keysym constants for modifier keys.
const (
	XKShiftL   = 0xFFE1
	XKShiftR   = 0xFFE2
	XKControlL = 0xFFE3
	XKControlR = 0xFFE4
	XKAltL     = 0xFFE9
	XKAltR     = 0xFFEA
	XKMetaL    = 0xFFE7
	XKMetaR    = 0xFFE8
	XKSuperL   = 0xFFEB
	XKSuperR   = 0xFFEC
)

// USB HID modifier key codes (0xE0-0xE7).
const (
	HIDLeftControl  = 0xE0
	HIDLeftShift    = 0xE1
	HIDLeftAlt      = 0xE2
	HIDLeftGUI      = 0xE3 // Super/Windows/Command
	HIDRightControl = 0xE4
	HIDRightShift   = 0xE5
	HIDRightAlt     = 0xE6
	HIDRightGUI     = 0xE7
)

// modifierKeysymMap maps X11 modifier keysyms to USB HID modifier key codes.
var modifierKeysymMap = map[uint32]byte{
	XKShiftL:   HIDLeftShift,
	XKShiftR:   HIDRightShift,
	XKControlL: HIDLeftControl,
	XKControlR: HIDRightControl,
	XKAltL:     HIDLeftAlt,
	XKAltR:     HIDRightAlt,
	XKMetaL:    HIDLeftGUI,
	XKMetaR:    HIDRightGUI,
	XKSuperL:   HIDLeftGUI,
	XKSuperR:   HIDRightGUI,

	// Additional modifier keysyms
	0xFFE5: 0x39, // Caps_Lock
}

